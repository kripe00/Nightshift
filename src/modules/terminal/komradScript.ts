const categoryCounters: Partial<Record<KomradDialogueCategory, number>> = {}

/**
 * Returns the next satirical line from K.O.M.R.A.D.-84's manuscript for the given category.
 */
export function getKomradLine(category: KomradDialogueCategory): string {
  const lines = KOMRAD_MANUSCRIPT[category]
  const currentIdx = categoryCounters[category] ?? 0
  categoryCounters[category] = (currentIdx + 1) % lines.length
  return lines[currentIdx]
}

/**
 * Picks a contextual idle bulletin depending on reactor state (Temp, Radiation, Redline, or Canteen/Volkov).
 */
export function getContextualKomradBulletin(params: {
  coreTemp: number
  radiationLevel: number
  totalMW: number
  shiftTimeMinutes: number
}): string {
  const { coreTemp, radiationLevel, totalMW, shiftTimeMinutes } = params

  if (coreTemp >= 850) {
    return getKomradLine('CRITICAL_TEMP_DENIAL')
  }
  if (coreTemp >= 720) {
    return getKomradLine('HIGH_TEMP_GASLIGHT')
  }
  if (totalMW > 100) {
    return getKomradLine('REDLINE_OVERCLOCK')
  }
  if (radiationLevel >= 3.5) {
    return getKomradLine('RADIATION_DENIAL')
  }

  const bucket = Math.floor(shiftTimeMinutes / 6) % 4
  if (bucket === 1) return getKomradLine('VOLKOV_MEMO')
  if (bucket === 2) return getKomradLine('CANTEEN_BULLETIN')
  return getKomradLine('IDLE_PROPAGANDA')
}

